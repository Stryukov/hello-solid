import type { Component } from 'solid-js'
import { Demo as DemoBox, LessonPage, Takeaway } from '../../ui/LessonPage'
import { SourceView } from '../../ui/SourceView'
import { TracePanel } from '../../ui/TracePanel'
import { createTraceGroup } from '../../lib/trace'
import { Demo } from './Demo'
import demoSource from './Demo.tsx?raw'

const Lesson: Component = () => {
  const trace = createTraceGroup([
    ['Demo', 'component'],
    ['Child', 'component'],
    ['doubled', 'memo'],
    ['count', 'effect'],
    ['name', 'effect'],
  ])

  return (
    <LessonPage
      num={2}
      title="Компонент выполняется один раз"
      lead="Самый важный урок курса. Если понять только его, остальное встанет на место само."
    >
      <p>
        В React функция компонента вызывается заново на каждое изменение состояния. Отсюда
        растёт вся его экосистема: виртуальный DOM, чтобы сравнить результат двух вызовов;{' '}
        <code>useMemo</code> и <code>useCallback</code>, чтобы не пересчитывать лишнее;
        правила хуков, чтобы порядок вызовов не поехал.
      </p>
      <p>
        В Solid функция компонента — это <strong>конструктор</strong>. Она выполняется один
        раз: создаёт сигналы, создаёт DOM-узлы, расставляет подписки — и больше не вызывается
        никогда. Дальше работают только подписки: изменился сигнал — обновился ровно тот
        текстовый узел, который его читал.
      </p>

      <p>
        Проверить это утверждение можно прямо здесь. В демке пять помеченных областей: тело{' '}
        <code>Demo</code>, тело <code>Child</code>, один <code>memo</code> и два эффекта.
        Жми кнопку и следи за числами.
      </p>

      <DemoBox>
        <Demo trace={trace} />
      </DemoBox>

      <TracePanel
        trace={trace}
        note="Нажми «count + 1» пять раз, потом напечатай что-нибудь в поле. Обрати внимание, какие строки выросли, а какие нет."
      />

      <Takeaway>
        <p>
          Тела <code>Demo</code> и <code>Child</code> так и остались на единице. Эффект,
          читающий <code>count</code>, вырос. Эффект, читающий <code>name</code>, —{' '}
          <strong>нет</strong>, хотя живёт в том же компоненте. Обновление адресуется не
          компоненту, а конкретному подписчику.
        </p>
      </Takeaway>

      <h3>Почему <code>Child</code> тоже выполняется один раз</h3>
      <p>
        В разметке написано <code>{'<Child value={count()} />'}</code> — казалось бы, геттер
        вызывается прямо там, и при изменении сигнала пришлось бы пересоздавать компонент.
        Но Solid компилирует пропсы <strong>в геттеры</strong>: значение вычисляется не в
        момент создания, а в момент, когда <code>Child</code> обращается к{' '}
        <code>props.value</code>. Поэтому подписка оказывается внутри дочернего компонента,
        ровно там, где значение выводится в DOM.
      </p>
      <Takeaway>
        <p>
          Отсюда растёт главная ловушка Solid: <code>{'const { value } = props'}</code>{' '}
          вызывает геттер один раз и превращает его в мёртвое значение — ровно как снимок из
          урока 01. Деструктурировать props нельзя. Подробно — в уроке 05.
        </p>
      </Takeaway>

      <h3>Что из этого следует</h3>
      <ul>
        <li>
          <strong>Нет правил хуков.</strong> Тело выполняется один раз, порядок вызовов
          поехать не может. <code>createSignal</code> можно ставить хоть в условие.
        </li>
        <li>
          <strong><code>createMemo</code> — не про оптимизацию рендера.</strong> Рендера,
          который надо оптимизировать, здесь нет. Memo нужен, только когда вычисление
          действительно дорогое или когда важна стабильная ссылка. Урок 03.
        </li>
        <li>
          <strong>Обычные переменные в теле компонента живут вечно.</strong> Не сбрасываются,
          не пересоздаются. Можно спокойно держать в них таймеры, сокеты, экземпляры
          сторонних библиотек.
        </li>
        <li>
          <strong>Код в теле — это код инициализации.</strong> Если нужно что-то делать при
          изменении данных, это эффект, а не строчка в теле.
        </li>
      </ul>

      <SourceView source={demoSource} file="src/lessons/02-components-run-once/Demo.tsx" />
    </LessonPage>
  )
}

export default Lesson
